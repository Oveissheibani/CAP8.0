class Runner:
    """Thread-based runner.  Owns the live process; pushes stdout lines
    into `output_q`.  GUI calls `tick_callback()` on the Tk thread."""

    def __init__(self, output_q: "queue.Queue[str]"):
        self.output_q = output_q
        self.proc: subprocess.Popen | None = None
        self._lock = threading.Lock()
        self.thread: threading.Thread | None = None
        self.aborted = False

    def is_running(self) -> bool:
        return self.thread is not None and self.thread.is_alive()

    def start(self, cmds: list[list[str]], state: dict,
              on_done: Callable[[], None]) -> None:
        if self.is_running():
            return
        self.aborted = False
        self.thread = threading.Thread(
            target=self._run, args=(cmds, state, on_done), daemon=True)
        self.thread.start()

    def stop(self) -> None:
        with self._lock:
            self.aborted = True
            if self.proc is None:
                return
            try:
                if os.name == "posix":
                    os.killpg(os.getpgid(self.proc.pid), signal.SIGTERM)
                else:
                    self.proc.terminate()
            except Exception:
                pass

    # --- internals ------------------------------------------------------
    def _emit(self, text: str, tag: str = "") -> None:
        # Encode tag inline as a leading sentinel the App splits out.
        if tag:
            self.output_q.put(f"\0{tag}\0{text}")
        else:
            self.output_q.put(text)

    def _run(self, cmds: list[list[str]], state: dict,
             on_done: Callable[[], None]) -> None:
        repo: Path = state["repo"]
        reports_dir = Path(state["outdir"]) / "reports"
        for i, argv in enumerate(cmds, 1):
            if self.aborted: break
            cwd = reports_dir if argv and argv[0] == "pdflatex" else None
            self._emit(f"\n=== [{i}/{len(cmds)}] "
                       + " ".join(shell_quote(x) for x in argv) + " ===\n",
                       "stage")
            try:
                with self._lock:
                    self.proc = subprocess.Popen(
                        argv,
                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                        text=True, bufsize=1,
                        cwd=str(cwd) if cwd else None,
                        preexec_fn=os.setsid if os.name == "posix" else None,
                    )
                assert self.proc.stdout is not None
                for line in self.proc.stdout:
                    self._emit(line)
                rc = self.proc.wait()
                with self._lock:
                    self.proc = None
                if rc != 0:
                    self._emit(f"\nstage {i} failed (exit {rc})\n", "error")
                    break
            except FileNotFoundError as exc:
                self._emit(f"\nmissing executable: {exc}\n", "error")
                break
            except Exception as exc:                       # noqa: BLE001
                self._emit(f"\ncrash: {exc!r}\n", "error")
                break
        self._emit("\n=== pipeline finished ===\n", "stage")
        on_done()
